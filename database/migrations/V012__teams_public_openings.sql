-- V012: v9 people round (A3) — teams master, public apply links + job descriptions on openings, careers applicants.
-- Hand-written and reviewed; never edit after it is applied — add a new migration.
--
-- 1. teams (decision D6) — a master entity: name, description, lead (a user), optional department, members (user ids).
--    A person may belong to several teams. People › Team groups people by team; with no teams it falls back to
--    departments. Managed under Admin › Organisation setup › Teams (master.view / master.edit).
--
-- 2. openings (decision D7) — a proper job description (about the role, responsibilities, requirements, nice to have,
--    location, work mode, employment type, experience range, optional salary range shown only when salary_visible) and
--    a public apply link: public_token (≥ 32 random URL-safe characters, unique across tenants; NULL = no link yet,
--    regenerating replaces it so the old link stops working). accepting_applications = false closes the link by hand;
--    the API also refuses applications unless the opening's status is open or interviewing. All new columns are
--    optional (absent on existing rows).
--
-- 3. candidates — applicants from the public careers page land with source 'careers' (UI "Careers link") and carry the
--    fields of the public form: LinkedIn URL, current company / title, location, cover note and the consent time.
--
-- 4. seereon_opening_tenant(token) — SECURITY DEFINER lookup of the tenant of a public apply token (the public page has
--    no session, so RLS would hide the row), like seereon_invite_tenant (V008). Only active / trial tenants answer.
--
-- No data change for existing rows.

