-- ---------------------------------------------------------------------------------------------------------------------
-- 4. tenant of a public apply token (no session → RLS hides the row)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE FUNCTION seereon_opening_tenant(p_token text) RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT o.tenant_id FROM openings o JOIN tenants t ON t.id = o.tenant_id
  WHERE o.public_token = p_token AND p_token ~ '^[A-Za-z0-9_-]{32,64}$' LIMIT 1
$$;
REVOKE EXECUTE ON FUNCTION seereon_opening_tenant(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION seereon_opening_tenant(text) TO seereon_app;
